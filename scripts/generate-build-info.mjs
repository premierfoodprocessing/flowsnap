import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const root = process.cwd();
const outJs = path.join(root, 'build-info.js');
const outWwwJs = path.join(root, 'www', 'build-info.js');
const outProps = path.join(root, 'android', 'build-info.properties');

function sh(cmd) {
  try { return execSync(cmd, { cwd: root, encoding: 'utf8', stdio: ['ignore','pipe','ignore'] }).trim(); }
  catch { return ''; }
}

const env = process.env;
const buildDate = env.FLOWSNAP_BUILD_DATE || sh("TZ=Africa/Lagos date '+%Y-%m-%d %H:%M:%S (Africa/Lagos)'");
const dateCompact = env.FLOWSNAP_BUILD_DATE_COMPACT || sh("TZ=Africa/Lagos date '+%Y%m%d'");
const timeCompact = env.FLOWSNAP_BUILD_TIME_COMPACT || sh("TZ=Africa/Lagos date '+%H%M%S'");
const versionName = env.FLOWSNAP_VERSION_NAME || `${buildDate.slice(0,10).replace(/-/g,'.')}-${timeCompact}-debug`;
const versionCode = String(env.FLOWSNAP_VERSION_CODE || Math.floor(Date.now()/1000));
const gitSha = env.FLOWSNAP_GIT_SHA || sh('git rev-parse HEAD');
const gitShort = env.FLOWSNAP_GIT_SHORT || sh('git rev-parse --short HEAD');
const gitBranch = env.FLOWSNAP_GIT_BRANCH || sh('git rev-parse --abbrev-ref HEAD');
const porcelain = sh('git status --porcelain');
const isDirty = porcelain.length > 0;
const dirtyFiles = porcelain ? porcelain.split('\n').filter(Boolean) : [];
const apkName = env.FLOWSNAP_APK_NAME || `flowsnap-debug-${dateCompact}.apk`;

const info = {
  productName: 'FlowSnap',
  applicationId: 'com.flowsnap.app',
  versionName,
  versionCode: Number(versionCode),
  buildNumber: String(versionCode),
  buildDateTime: buildDate,
  buildType: 'Debug',
  gitCommitSha: gitSha,
  gitCommitShort: gitShort,
  gitBranch,
  worktreeClean: !isDirty,
  uncommittedChanges: dirtyFiles,
  apkFileName: apkName,
};

const js = `// Generated by scripts/generate-build-info.mjs. Do not hand-edit.\nwindow.__FLOWSNAP_BUILD__ = ${JSON.stringify(info, null, 2)};\n`;
fs.writeFileSync(outJs, js);
fs.mkdirSync(path.dirname(outWwwJs), { recursive: true });
fs.writeFileSync(outWwwJs, js);

const esc = (v) => String(v).replace(/\\/g,'\\\\').replace(/\n/g,'\\n');
const props = [
  `FLOWSNAP_VERSION_NAME=${esc(versionName)}`,
  `FLOWSNAP_VERSION_CODE=${esc(versionCode)}`,
  `FLOWSNAP_BUILD_DATE=${esc(buildDate)}`,
  `FLOWSNAP_GIT_SHA=${esc(gitSha)}`,
  `FLOWSNAP_GIT_SHORT=${esc(gitShort)}`,
  `FLOWSNAP_GIT_BRANCH=${esc(gitBranch)}`,
  `FLOWSNAP_WORKTREE_CLEAN=${isDirty ? 'false' : 'true'}`,
  `FLOWSNAP_APK_NAME=${esc(apkName)}`,
  `FLOWSNAP_BUILD_TYPE=Debug`,
].join('\n') + '\n';
fs.mkdirSync(path.dirname(outProps), { recursive: true });
fs.writeFileSync(outProps, props);

console.log(JSON.stringify(info, null, 2));
